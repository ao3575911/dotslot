"""Generate npm/src/tables.ts from the Python wcwidth package (the reference width model).
Run with the dotslot venv: python npm/scripts/gen_tables.py"""
import os, sys, wcwidth
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..'))
from dotslot.width import _extends
from wcwidth.table_vs16 import VS16_NARROW_TO_WIDE
from wcwidth.table_vs15 import VS15_WIDE_TO_NARROW

def ranges(pred):
    out, start = [], None
    for c in range(0x110000 + 1):
        ok = c < 0x110000 and not (0xD800 <= c <= 0xDFFF) and pred(c)
        if ok and start is None: start = c
        if not ok and start is not None: out.append((start, c - 1)); start = None
    return out

w = {}
def width(c):
    if c not in w: w[c] = wcwidth.wcwidth(chr(c))
    return w[c]
def flat(rs): return ''.join(f'\n  0x{a:x}, 0x{b:x},' for a, b in ((r if isinstance(r, tuple) else (r, r)) for r in rs)) + '\n'
tabs = dict(WIDE=ranges(lambda c: width(c) == 2), ZERO=ranges(lambda c: width(c) == 0),
            CTRL=ranges(lambda c: width(c) < 0), EXTEND=ranges(lambda c: bool(_extends(chr(c)))),
            VS16=list(VS16_NARROW_TO_WIDE['9.0.0']), VS15=list(VS15_WIDE_TO_NARROW['9.0.0']))
out = [f'// Generated by scripts/gen_tables.py from Python wcwidth {wcwidth.__version__}. Do not edit.', '// Each line is one inclusive [start, end] code point range.']
for k, v in tabs.items(): out.append(f'export const {k}: readonly number[] = [{flat(v)}];')
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'tables.ts'), 'w').write('\n'.join(out) + '\n')
print({k: len(v) for k, v in tabs.items()})
